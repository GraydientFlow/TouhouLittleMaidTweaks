package io.github.graydients.tlmtweaks.mixin;

import io.github.graydients.tlmtweaks.pickup.PickupDelay;
import net.minecraft.world.entity.item.ItemEntity;
import net.minecraft.world.item.ItemStack;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(ItemEntity.class)
public abstract class ItemDropTimeMixin {
    @Inject(method = "merge(Lnet/minecraft/world/entity/item/ItemEntity;Lnet/minecraft/world/item/ItemStack;Lnet/minecraft/world/entity/item/ItemEntity;Lnet/minecraft/world/item/ItemStack;)V", at = @At("TAIL"))
    private static void keepNewestDropTime(ItemEntity destination, ItemStack destinationStack,
                                          ItemEntity source, ItemStack sourceStack, CallbackInfo callback) {
        PickupDelay.merged(destination, source);
    }
}
