package io.github.graydients.tlmtweaks.mixin;

import io.github.graydients.tlmtweaks.client.GhostGateView;
import net.minecraft.core.BlockPos;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.state.BlockState;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable;

@Mixin(Level.class)
public abstract class GhostGateClientStateMixin {
    @Inject(method="setBlock(Lnet/minecraft/core/BlockPos;Lnet/minecraft/world/level/block/state/BlockState;II)Z",at=@At("RETURN"))
    private void changed(BlockPos pos,BlockState state,int flags,int recursion,CallbackInfoReturnable<Boolean> callback) {
        if(callback.getReturnValueZ())GhostGateView.changed((Level)(Object)this,pos,state);
    }
}
