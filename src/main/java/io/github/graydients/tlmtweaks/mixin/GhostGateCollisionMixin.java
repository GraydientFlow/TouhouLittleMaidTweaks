package io.github.graydients.tlmtweaks.mixin;

import io.github.graydients.tlmtweaks.gates.GhostGates;
import net.minecraft.core.BlockPos;
import net.minecraft.world.level.BlockGetter;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.phys.shapes.CollisionContext;
import net.minecraft.world.phys.shapes.VoxelShape;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable;

@Mixin(BlockBehaviour.BlockStateBase.class)
public abstract class GhostGateCollisionMixin {
    @Inject(method="getCollisionShape(Lnet/minecraft/world/level/BlockGetter;Lnet/minecraft/core/BlockPos;Lnet/minecraft/world/phys/shapes/CollisionContext;)Lnet/minecraft/world/phys/shapes/VoxelShape;",at=@At("HEAD"),cancellable=true)
    private void ghostCollision(BlockGetter blocks,BlockPos pos,CollisionContext context,CallbackInfoReturnable<VoxelShape> callback) {
        if(blocks instanceof Level level) { var shape=GhostGates.collision(level,pos,(BlockState)(Object)this,context);if(shape!=null) callback.setReturnValue(shape); }
    }
}
